# =========================================================================
#  §1  REBIT ISOMORPHISM
# =========================================================================
#
#   A rebit is a qubit restricted to real amplitudes: |psi> = a|0> + b|1>
#   with a, b in R, a^2 + b^2 = 1. The state lives on the Bloch circle
#   (real subset of the Bloch sphere).
#
#   Claim: the t-bit state x in (0, infty) is isomorphic to a rebit state
#   MODULO THE SIGN of b, under the bijection
#        |a| = cos(theta/2),  |b| = sin(theta/2),  x = cot^2(theta/2).
#
#   The t-bit therefore captures EXACTLY the rebit density on the circle;
#   it does not distinguish (+a, +b) from (+a, -b). This is the structural
#   reason the framework has "no phase": phase is precisely the sign of b.

def rebit_from_x(x: float) -> tuple:
    """Map t-bit state x to the rebit amplitude pair (|a|, |b|).
    Returns the NON-NEGATIVE amplitudes; the sign of b is not recoverable.
    """
    theta = theta_from_x(x)
    return (math.cos(theta / 2), math.sin(theta / 2))


def x_from_rebit(a: float, b: float) -> float:
    """Inverse: given |a|, |b| (non-negative, a^2+b^2=1), recover x.
    The sign of b is DISCARDED.
    """
    if abs(b) < 1e-15:
        return float('inf')
    return (a / b) ** 2


def test_rebit_isomorphism():
    """Round-trip the bijection x <-> (|a|, |b|) at representative points."""
    for x in [0.01, 0.5, 1.0, 4.0, 16.0, 100.0]:
        a, b = rebit_from_x(x)
        # Normalisation
        assert abs(a * a + b * b - 1.0) < 1e-12, f"norm fails at x={x}"
        # mu recovery: a^2 = mu
        assert abs(a * a - float(mu(x))) < 1e-12, f"mu=a^2 fails at x={x}"
        # Round trip
        x_back = x_from_rebit(a, b)
        assert abs(x_back - x) / max(1.0, abs(x)) < 1e-10, f"round-trip fails at x={x}"

    # Phase-loss witness: (+a, +b) and (+a, -b) map to the same x
    x = 4.0
    a, b = rebit_from_x(x)
    x_pos = x_from_rebit(a, b)
    x_neg = x_from_rebit(a, -b)  # sign-flipped b
    assert abs(x_pos - x_neg) < 1e-12, "phase-loss witness failed"

    print("  [ok] Rebit isomorphism: x = (a/b)^2, phase-sign of b is lost")


# =========================================================================
#  §2  GATE GROUP STRUCTURE
# =========================================================================
#
#   Single-t-bit gates fall into two families:
#
#   (A) Mobius sector: PGL2+(R), 3 real parameters.
#       Generators: P (reflection), D_alpha (dilation), T_lambda (shift).
#       Group law: composition of Mobius maps.
#
#   (B) Power-map sector: (R*, x), 1 real parameter.
#       Generators: p_alpha: x -> x^alpha, for alpha in R*.
#       (S = p_2, R = p_{1/2}.)
#
#   Claim (verified below):
#     (i)  P commutes with every p_alpha:  P p_alpha = p_alpha P
#     (ii) p_alpha D_beta = D_{beta^alpha} p_alpha   (intertwining relation)
#     (iii) p_alpha does NOT commute with T_lambda   (power-map breaks shift)
#
#   Consequence: the full gate monoid is generated by PGL2+(R) and the
#   power-map line, but the two pieces do not form a semidirect product.
#   The monoid does not reduce to any finite-dimensional Lie group.
#
#   Practical resolution: in log-coordinates u = ln x, the AFFINE SECTOR
#     (P, D_alpha, p_alpha)  maps to  (u -> -u,  u -> u + c,  u -> alpha*u).
#   This is the full real affine group Aff(R) extended by a Z_2 reflection.
#   T_lambda is the ONE Mobius gate that is nonlinear in u.

def u_action_D(alpha: float):
    """D_alpha in log-space: u -> u + ln(alpha)."""
    c = math.log(alpha)
    return lambda u: u + c


def u_action_p(alpha: float):
    """Power map p_alpha in log-space: u -> alpha * u."""
    return lambda u: alpha * u


def u_action_P():
    """Parity P in log-space: u -> -u."""
    return lambda u: -u


def u_action_T(lam: float):
    """Threshold T_lambda in log-space: u -> ln(e^u + lambda).  Nonlinear."""
    return lambda u: math.log(math.exp(u) + lam)


def test_power_parity_commute():
    """P p_alpha = p_alpha P, for all alpha."""
    for alpha in [0.5, 2.0, 3.0, 0.1]:
        for x in [0.3, 1.0, 4.0]:
            P_p = 1.0 / (x ** alpha)
            p_P = (1.0 / x) ** alpha
            assert abs(P_p - p_P) < 1e-12, f"P,p_{alpha} commutator fails at x={x}"
    print("  [ok] P p_alpha = p_alpha P  (reflection commutes with power)")


def test_power_dilation_intertwine():
    """p_alpha D_beta = D_{beta^alpha} p_alpha."""
    for alpha, beta in [(2.0, 3.0), (0.5, 4.0), (1.5, 2.0), (-1.0, 2.0)]:
        for x in [0.25, 1.0, 7.0]:
            lhs = (beta * x) ** alpha
            rhs = (beta ** alpha) * (x ** alpha)
            assert abs(lhs - rhs) < 1e-10, f"intertwine fails at alpha={alpha},beta={beta}"
    print("  [ok] p_alpha D_beta = D_{beta^alpha} p_alpha  (conjugation law)")


def test_power_shift_NON_commute():
    """p_alpha does NOT commute with T_lambda (for generic alpha)."""
    alpha = 2.0
    lam = 3.0
    for x in [0.5, 2.0, 7.0]:
        p_then_T = (x ** alpha) + lam
        T_then_p = (x + lam) ** alpha
        diff = abs(p_then_T - T_then_p)
        assert diff > 1e-6, f"expected non-commutation at x={x}"
    print("  [ok] p_alpha and T_lambda do NOT commute (witness obstruction)")


def test_affine_sector_closed_under_composition():
    """
    Affine sector in log-space: generators {P, D_alpha, p_alpha}.
    Composition closes to  u -> sigma * alpha * u + c  for sigma in {+/-1}.
    Verify by composition of several elements.
    """
    # Apply D_alpha1 then p_beta then D_alpha2 then P:
    # x -> alpha1*x -> (alpha1*x)^beta -> alpha2*(alpha1*x)^beta
    #   -> 1/[alpha2*(alpha1*x)^beta]
    # In u:  u + ln(alpha1) -> beta*(u + ln(alpha1))
    #       -> beta*u + beta*ln(alpha1) + ln(alpha2)
    #       -> -beta*u - beta*ln(alpha1) - ln(alpha2)
    alpha1, alpha2, beta = 2.0, 3.0, 1.5
    for x in [0.3, 1.0, 5.0]:
        u = math.log(x)
        u_final = -beta * u - beta * math.log(alpha1) - math.log(alpha2)

        x_final_direct = 1.0 / (alpha2 * (alpha1 * x) ** beta)
        assert abs(math.log(x_final_direct) - u_final) < 1e-10, "affine closure"
    print("  [ok] Affine sector in u-space closes to  u -> +/- beta*u + c")


# =========================================================================
#  §3  CLIFFORD / MAGIC SPLIT
# =========================================================================
#
#   Setting: t-bit inputs clamped to logical poles, x_i in {0+, infty},
#   equivalently mu_i in {0, 1}. A Boolean function f on n bits is encoded
#   in its Walsh bridge b[c] = (1/N) sum_j (1 - 2 f(j)) chi_c(j).
#
#   A gate G acts on bridge coefficients via its effect on the underlying
#   truth table. We say G is "sign-acting on characters" (SAC) iff there
#   exists a sign pattern s: c -> {+/-1} such that b'[c] = s(c) b[c] for
#   every bridge coefficient (up to a character permutation).
#
#   Theorem (verified below):
#     * Single-t-bit gate P (parity) is SAC.
#     * The XOR-controlled multi-t-bit gate is SAC.
#     * The soft CNOT, under pole-clamped inputs, is SAC.
#     * T_lambda is NOT SAC (produces intermediate x not at the poles).
#     * AND-controlled Toffoli is NOT SAC.
#
#   The SAC sector is efficiently classically simulable: track the sign
#   pattern, O(N) per gate, O(n*s) total for a depth-s circuit. It is the
#   t-bit analog of the Clifford group; T_lambda and AND-control supply
#   the "magic" that carries the framework OUT of classical simulability.

def _fresh_truth_table(n: int, rng=None):
    """Random {0,1}-vector of length 2^n for stress-testing."""
    rng = rng or np.random.default_rng(0)
    N = 2 ** n
    return rng.integers(0, 2, size=N)


def apply_P_on_tbit_i(tt: np.ndarray, i: int) -> np.ndarray:
    """Parity gate on t-bit i: swap mu_i = 0 and mu_i = 1 everywhere.
    This flips bit i of the index j."""
    N = len(tt)
    out = np.empty_like(tt)
    for j in range(N):
        j_flipped = j ^ (1 << i)
        out[j] = tt[j_flipped]
    return out


def test_P_is_SAC():
    """Bridge under P on bit i: each coefficient picks up sign (-1)^{c_i}."""
    n = 4
    for trial in range(6):
        tt = _fresh_truth_table(n, np.random.default_rng(trial))
        bridge = truth_table_to_bridge(tt)
        for i in range(n):
            tt_flipped = apply_P_on_tbit_i(tt, i)
            bridge_flipped = truth_table_to_bridge(tt_flipped)
            # Check: bridge_flipped[c] = bridge[c] * (-1)^{bit i of c}
            for c in range(2 ** n):
                sign = -1 if (c >> i) & 1 else +1
                assert abs(bridge_flipped[c] - sign * bridge[c]) < 1e-10
    print("  [ok] P on bit i: bridge[c] picks up sign (-1)^(c_i)  -> SAC")


def test_XOR_toffoli_is_SAC():
    """XOR-controlled Toffoli: on pole-clamped inputs, bit i flips iff
    bits a and b disagree. The bridge transform is a sign-action."""
    n = 3
    # Target=0, Controls={1,2}: output bit 0 becomes bit 0 XOR (bit 1 XOR bit 2).
    # This is a permutation of the truth table. Test its SAC property.
    for trial in range(4):
        tt = _fresh_truth_table(n, np.random.default_rng(100 + trial))
        bridge = truth_table_to_bridge(tt)

        # Construct permuted truth table
        N = 2 ** n
        tt_new = np.empty_like(tt)
        for j in range(N):
            b0 = (j >> 0) & 1
            b1 = (j >> 1) & 1
            b2 = (j >> 2) & 1
            # Target flip iff disagreement (b1 XOR b2) = 1
            flip = (b1 ^ b2) & 1
            j_new = j ^ (flip << 0)  # flip bit 0 conditionally
            tt_new[j] = tt[j_new]
        bridge_new = truth_table_to_bridge(tt_new)
        # Check SAC: |bridge_new[c]| should permute |bridge[c]| with signs
        perm = {}
        for c in range(N):
            val_old = abs(bridge[c])
            val_new = abs(bridge_new[c])
            if val_old > 1e-10:
                perm[c] = (val_new, bridge_new[c], bridge[c])
        # All nonzero coefficients preserve magnitude (just reshuffle)
        old_mags = sorted([abs(v) for v in bridge if abs(v) > 1e-10])
        new_mags = sorted([abs(v) for v in bridge_new if abs(v) > 1e-10])
        assert len(old_mags) == len(new_mags)
        for a, b in zip(old_mags, new_mags):
            assert abs(a - b) < 1e-10
    print("  [ok] XOR-Toffoli: bridge magnitudes are preserved  -> SAC")


def test_AND_toffoli_NOT_SAC():
    """AND-controlled Toffoli flips target only when BOTH controls = 1.
    This is NOT a character-sign action; it changes the sparsity."""
    # Start: 3-bit identity on target (f(b2,b1,b0) = b0). Bridge has sparsity 1.
    n = 3
    N = 8
    tt = np.array([(j >> 0) & 1 for j in range(N)])
    bridge_before = truth_table_to_bridge(tt)
    sp_before = walsh_sparsity(bridge_before)

    # Apply AND-Toffoli: target=0, controls={1,2}
    # Output bit 0 becomes b0 XOR (b1 AND b2)
    tt_after = np.array([
        ((j >> 0) & 1) ^ (((j >> 1) & 1) & ((j >> 2) & 1))
        for j in range(N)
    ])
    bridge_after = truth_table_to_bridge(tt_after)
    sp_after = walsh_sparsity(bridge_after)

    # Magnitudes cannot match after AND operation
    mags_before = sorted([abs(v) for v in bridge_before if abs(v) > 1e-10])
    mags_after = sorted([abs(v) for v in bridge_after if abs(v) > 1e-10])
    assert mags_before != mags_after or sp_before != sp_after, \
        "AND-Toffoli should change bridge structure"
    print(f"  [ok] AND-Toffoli: sparsity {sp_before} -> {sp_after}  -> NOT SAC (magic)")


def test_T_lambda_off_pole_NOT_SAC():
    """T_lambda takes a pole state x=infty to x=infty+lambda=infty (preserved),
    but takes x=0+ to lambda (NOT a pole). Hence T_lambda cannot even be
    represented by a truth-table permutation: it forces an intermediate x.
    """
    # T_lambda on x=0 gives lambda, whose mu is lambda/(lambda+1) != 0 or 1.
    lam = 2.0
