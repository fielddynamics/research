def cgate_P(cb: CBit) -> CBit:
    """Parity gate: swap alpha <-> beta.  Equivalently x -> 1/x.
    Phase of beta is preserved (it transfers to alpha, which is then
    phase-normalised by the CBit constructor)."""
    return CBit(alpha=cb.beta, beta=cb.alpha)


def cgate_D(cb: CBit, alpha: float) -> CBit:
    """Dilation x -> alpha * x.  In amplitude form:
        |alpha_new|^2 / |beta_new|^2 = alpha * |alpha_old|^2 / |beta_old|^2
    Keep the phase of beta, redistribute magnitudes.
    """
    if alpha <= 0:
        raise ValueError("D requires alpha > 0")
    new_x = alpha * cb.x
    return CBit(x=new_x, phi=cb.phi)


def cgate_Phi(cb: CBit, delta: float) -> CBit:
    """Phase gate: beta -> beta * e^{i delta}.  Alpha unchanged."""
    return CBit(alpha=cb.alpha, beta=cb.beta * cmath.exp(1j * delta))


# Standard Hadamard matrix
_H_MATRIX = (1.0 / math.sqrt(2.0)) * np.array(
    [[1, 1],
     [1, -1]], dtype=complex
)


def cgate_H(cb: CBit) -> CBit:
    """True Hadamard, order 2.  Acts by matrix multiplication on (alpha, beta):
        (alpha', beta') = H @ (alpha, beta)
    Specifically:
        |0>_g  ->  |+>_g   (theta=0, phi=0) -> (theta=pi/2, phi=0)
        |1>_g  ->  |->_g   (theta=pi, phi=0) -> (theta=pi/2, phi=pi)
        |+>_g  ->  |0>_g
        |->_g  ->  |1>_g
    """
    amp = cb.amplitudes()
    new_amp = _H_MATRIX @ amp
    return CBit(alpha=new_amp[0], beta=new_amp[1])


def cgate_S_phase(cb: CBit) -> CBit:
    """S (phase) gate: beta -> i * beta.  Order 4 (S^2 = Z, S^4 = I).
    This is the standard Clifford S gate, distinct from the power-map S."""
    return CBit(alpha=cb.alpha, beta=1j * cb.beta)


def cgate_Z(cb: CBit) -> CBit:
    """Z gate: beta -> -beta.  Z = S^2, order 2."""
    return CBit(alpha=cb.alpha, beta=-cb.beta)


def test_cgate_Phi_is_phase_rotation():
    """Phase gate composition: Phi(a) then Phi(b) = Phi(a+b)."""
    cb = CBit(x=4.0, phi=0.3)
    cb1 = cgate_Phi(cgate_Phi(cb, 0.5), 0.7)
    cb2 = cgate_Phi(cb, 1.2)
    # Compare amplitudes up to global phase (already normalised out by constructor)
    a1, b1 = cb1.alpha, cb1.beta
    a2, b2 = cb2.alpha, cb2.beta
    assert abs(a1 - a2) < 1e-12, f"alpha mismatch: {a1} vs {a2}"
    assert abs(b1 - b2) < 1e-12, f"beta  mismatch: {b1} vs {b2}"
    print("  [ok] Phase gate: Phi(a) Phi(b) = Phi(a+b)")


def test_cgate_H_is_involution():
    """Standard Hadamard: H^2 = I on every basis state and arbitrary input."""
    test_states = [
        CBit(alpha=1.0, beta=0.0),    # |0>_g
        CBit(alpha=0.0, beta=1.0),    # |1>_g
        CBit(alpha=1/math.sqrt(2), beta=1/math.sqrt(2)),   # |+>_g
        CBit(alpha=1/math.sqrt(2), beta=-1/math.sqrt(2)),  # |->_g
        CBit(x=4.0, phi=math.pi / 3),     # generic
        CBit(x=0.25, phi=1.7),            # generic
    ]
    for cb in test_states:
        cb_HH = cgate_H(cgate_H(cb))
        # Amplitudes match up to the constructor's phase-normalisation.
        # Compare theta and phi: both should match.
        dtheta = abs(cb.theta - cb_HH.theta)
        # phi undefined if |beta| = 0, so guard
        if abs(cb.beta) > 1e-10 and abs(cb_HH.beta) > 1e-10:
            dphi = min(
                abs(cb.phi - cb_HH.phi),
                abs(cb.phi - cb_HH.phi - 2 * math.pi),
                abs(cb.phi - cb_HH.phi + 2 * math.pi),
            )
        else:
            dphi = 0.0
        assert dtheta < 1e-10 and dphi < 1e-10, \
            f"H^2 != Id: theta diff {dtheta}, phi diff {dphi}"
    print("  [ok] H^2 = Id on all test states (true involution)")


def test_cgate_H_basis_action():
    """H maps |0> <-> |+>, |1> <-> |->.  Check all four."""
    # |0>_g -> |+>_g
    cb = CBit(alpha=1.0, beta=0.0)
    out = cgate_H(cb)
    assert abs(out.alpha - 1 / math.sqrt(2)) < 1e-12
    assert abs(out.beta - 1 / math.sqrt(2)) < 1e-12

    # |1>_g -> |->_g
    cb = CBit(alpha=0.0, beta=1.0)
    out = cgate_H(cb)
    assert abs(out.alpha - 1 / math.sqrt(2)) < 1e-12
    assert abs(out.beta - (-1 / math.sqrt(2))) < 1e-12

    # |+>_g -> |0>_g
    cb = CBit(alpha=1 / math.sqrt(2), beta=1 / math.sqrt(2))
    out = cgate_H(cb)
    assert abs(out.alpha - 1.0) < 1e-12
    assert abs(out.beta) < 1e-12

    # |->_g -> |1>_g
    # Note: the constructor phase-normalises; -1/sqrt(2) alpha becomes +1/sqrt(2)
    # with a sign absorbed into beta.  But H|-> = |1> = (0, 1), alpha=0 is fine.
    cb = CBit(alpha=1 / math.sqrt(2), beta=-1 / math.sqrt(2))
    out = cgate_H(cb)
    # Output is (0, -1); after phase normalisation: alpha=0 is unchanged, beta=-1.
    # But our constructor absorbs a global phase from alpha, not beta.
    # With alpha = 0, we cannot absorb a phase (no reference).
    # So the output beta may be -1 rather than +1.  Test via |beta|^2 = 1.
    assert abs(abs(out.beta) ** 2 - 1.0) < 1e-12
    assert abs(out.alpha) < 1e-12
    print("  [ok] H acts correctly on |0>, |1>, |+>, |-> basis states")


def test_S_Z_phase_algebra():
    """S^2 = Z, S^4 = I."""
