# =========================================================================
#  §5  DENSITY-MATRIX FORMALISM
# =========================================================================
#
#   The c-bit state maps to a 2x2 HERMITIAN density matrix:
#       rho = [[|alpha|^2,  alpha * conj(beta)],
#              [conj(alpha)*beta,  |beta|^2]]
#           = [[mu,               sqrt(mu mubar) e^{-i phi}],
#              [sqrt(mu mubar) e^{i phi},  mubar]]
#   Trace = 1, positive semidefinite, rank 1 for pure states.
#   The t-bit state corresponds to phi = 0  (real density, rebit).

def cbit_density(cb: CBit) -> np.ndarray:
    mu_val = cb.mu
    mubar = 1.0 - mu_val
    off = math.sqrt(mu_val * mubar)
    return np.array([
        [mu_val,                off * cmath.exp(-1j * cb.phi)],
        [off * cmath.exp(1j * cb.phi),  mubar],
    ], dtype=complex)


def test_density_matrix_properties():
    """Trace=1, Hermitian, PSD, rank 1."""
    for x, phi in [(0.25, 0.0), (1.0, math.pi / 3), (4.0, math.pi / 2),
                   (16.0, math.pi)]:
        cb = CBit(x=x, phi=phi)
        rho = cbit_density(cb)
        # Trace
        assert abs(np.trace(rho) - 1.0) < 1e-12
        # Hermitian
        assert np.allclose(rho, rho.conj().T, atol=1e-12)
        # Eigenvalues: one is 1, other is 0 (pure state)
        eigs = np.sort(np.real(np.linalg.eigvalsh(rho)))
        assert abs(eigs[0]) < 1e-10 and abs(eigs[1] - 1.0) < 1e-10
        # Purity: Tr(rho^2) = 1
        purity = np.real(np.trace(rho @ rho))
        assert abs(purity - 1.0) < 1e-12
    print("  [ok] Density matrix: trace=1, Hermitian, rank 1, pure (Tr rho^2 = 1)")


def test_tbit_is_real_density_slice():
    """At phi=0, the c-bit density is REAL (rebit slice)."""
    for x in [0.25, 1.0, 4.0]:
        cb = CBit(x=x, phi=0.0)
        rho = cbit_density(cb)
        assert np.max(np.abs(rho.imag)) < 1e-14, "phi=0 -> real density"
    print("  [ok] C-bit at phi=0 is REAL density matrix  =  rebit slice  =  t-bit")


# =========================================================================
#  §6  POVM MEASUREMENT
# =========================================================================
#
#   The "partition triple" R(x) = (mu, mubar, mu mubar) sums to
#     mu + mubar + mu*mubar != 1 in general,
#   so it is not a POVM as stated. However, the natural POVM is
#     E_0 = |0>_g <0|_g = [[1,0],[0,0]],
#     E_1 = |1>_g <1|_g = [[0,0],[0,1]],
#     E_? = |+>_g <+|_g - (1/2)(E_0 + E_1)  (transition-rate witness)
#   or, more cleanly, the projective TWO-outcome POVM {E_0, E_1} with the
#   third component (mu*mubar) being the two-point CORRELATOR, not a
#   probability. Let's fix this explicitly.

def povm_two_outcome():
    """Projective POVM {E_0, E_1} with E_0 + E_1 = I."""
    E0 = np.array([[1, 0], [0, 0]], dtype=complex)
    E1 = np.array([[0, 0], [0, 1]], dtype=complex)
    return E0, E1


def povm_outcome_probs(cb: CBit):
    """Born rule against the projective POVM."""
    rho = cbit_density(cb)
    E0, E1 = povm_two_outcome()
    p0 = np.real(np.trace(rho @ E0))
    p1 = np.real(np.trace(rho @ E1))
    return float(p0), float(p1)


def test_povm_completeness():
    E0, E1 = povm_two_outcome()
    assert np.allclose(E0 + E1, np.eye(2, dtype=complex)), "POVM not complete"
    # Positive semi-definite
    for E in (E0, E1):
        eigs = np.real(np.linalg.eigvalsh(E))
        assert all(e >= -1e-12 for e in eigs)
    print("  [ok] Projective POVM {E_0, E_1}: complete, PSD")


def test_povm_matches_partition_fractions():
    """Tr(rho E_0) = mu,  Tr(rho E_1) = 1-mu.  Independent of phase."""
    for x, phi in [(0.25, 0.0), (1.0, 1.3), (4.0, 2.7), (16.0, 0.0)]:
        cb = CBit(x=x, phi=phi)
        p0, p1 = povm_outcome_probs(cb)
        assert abs(p0 - float(mu(x))) < 1e-12
        assert abs(p1 - float(one_minus_mu(x))) < 1e-12
        assert abs(p0 + p1 - 1.0) < 1e-12
    print("  [ok] POVM probs match (mu, mubar); phase-invariant (as expected)")


def test_transition_rate_is_coherence():
    """mu * mubar is the SQUARED MAGNITUDE of the off-diagonal (coherence).
    It is phase-invariant, and peaks at mu = 1/2 where it equals 1/4."""
    for x in [0.25, 1.0, 4.0, 16.0]:
        cb = CBit(x=x, phi=1.3)  # arbitrary phase
        rho = cbit_density(cb)
        off_sq = abs(rho[0, 1]) ** 2
        mu_val = float(mu(x))
        expected = mu_val * (1.0 - mu_val)
        assert abs(off_sq - expected) < 1e-12
    print("  [ok] Transition rate mu*mubar = |rho_{01}|^2  (coherence magnitude)")


# =========================================================================
#  §7  CIRCUIT DEPTH, HONEST
# =========================================================================
#
#   The markdown claims "t-bit XOR depth = 1 vs classical depth = n". That
#   is misleading: classical *serial* XOR is depth n, but classical
#   *parallel* XOR is depth O(log n) via a binary tree of 2-input XORs.
#   Honest statement: the t-bit architecture gives a SPARSITY-optimal
#   WaveNode count, equal to the Walsh sparsity s(f). For XOR this is 1;
#   for AND this is 2^n. The advantage over classical parallel depth is
#   at most log(n) for structured functions, not exponential.
#
#   Genuine hardware advantage: single-cycle evaluation regardless of n
#   (no gate chain latency), provided the WaveNode sums all bridge terms
#   in parallel. The ASYMPTOTIC depth matches parallel classical.

def classical_parallel_depth_xor(n: int) -> int:
    """Binary tree of 2-input XORs: depth = ceil(log2(n))."""
    return math.ceil(math.log2(max(n, 1)))


def tbit_depth_xor(n: int) -> int:
    """Single WaveNode evaluation of the full-parity character: depth 1."""
    N = 2 ** n
    tt = np.array([bin(i).count('1') % 2 for i in range(N)])
    bridge = truth_table_to_bridge(tt)
    return walsh_sparsity(bridge)


def test_depth_xor_honest():
    """For n=8: classical parallel depth = 3, t-bit depth = 1.
    Advantage: constant (3) vs constant (1) -- a THREE-FOLD speedup for
    n=8, growing as log n. Not exponential.
    """
    for n in [2, 4, 8, 16]:
        c_depth = classical_parallel_depth_xor(n)
        t_depth = tbit_depth_xor(n)
        ratio = c_depth / t_depth if t_depth else float('inf')
        # t-bit always 1; classical grows as log2(n)
        assert t_depth == 1
        assert c_depth == math.ceil(math.log2(n))
    print("  [ok] XOR depth: t-bit = 1, classical parallel = log2(n). "
          "Advantage is log n, not exponential.")


def test_depth_and_worst_case():
    """For AND of n bits: t-bit depth = 2^n (all bridge coeffs nonzero),
    classical parallel depth = log2(n). t-bit is EXPONENTIALLY WORSE.
    This shows the t-bit architecture has a computational COST for
    monotone functions, not a universal speedup."""
    for n in [2, 3, 4, 5]:
        N = 2 ** n
        tt = np.zeros(N, dtype=int)
        tt[-1] = 1  # AND is 1 only when all bits set
        bridge = truth_table_to_bridge(tt)
        s = walsh_sparsity(bridge)
        c_depth = math.ceil(math.log2(n))
        assert s == N, f"AND sparsity {s} != {N}"
        assert s > c_depth or n <= 2, \
            f"t-bit {s} should exceed classical {c_depth} for n>2"
    print("  [ok] AND depth: t-bit = 2^n, classical parallel = log n. "
          "t-bit is EXP WORSE for monotone functions.")


# =========================================================================
#  §8  TWO-QUBIT C-GATE AND RECOVERED PHASE
# =========================================================================
#
#   Two-c-bit controlled phase: |c,t> -> e^{i phi c*t} |c,t>. Standard
#   Clifford-like primitive. We implement it on the density formalism and
#   verify it preserves purity, changes off-diagonals, and is order-1 in
#   phase rotation.

def two_cbit_cphase(cb_c: CBit, cb_t: CBit, phi: float):
    """Controlled phase: applies phase phi when BOTH c-bits are at |1>_g.
    Action on 2-qubit amplitudes:
        alpha_c alpha_t -> itself                (both |0>)
        alpha_c beta_t  -> itself                (c=|0>, t=|1>)
        beta_c  alpha_t -> itself                (c=|1>, t=|0>)
        beta_c  beta_t  -> e^{i phi} beta_c beta_t   (both |1>)
    We return the updated pair and the joint phase added to the beta-beta
    component. Normalisation is preserved.
    """
    # For two individual c-bits, the controlled phase is nonlocal and
    # cannot be separated. Return the 2-qubit amplitude vector.
    a_c, b_c = cb_c.alpha, cb_c.beta
    a_t, b_t = cb_t.alpha, cb_t.beta
    # Joint amplitudes, order |00>,|01>,|10>,|11>
    amp = np.array([
        a_c * a_t,
        a_c * b_t,
        b_c * a_t,
        b_c * b_t * cmath.exp(1j * phi),
    ])
    return amp


def test_cphase_preserves_norm():
    for phi in [0.0, math.pi / 3, math.pi]:
        cb_c = CBit(x=1.0, phi=0.0)
        cb_t = CBit(x=1.0, phi=0.0)
        amp = two_cbit_cphase(cb_c, cb_t, phi)
        norm = sum(abs(a) ** 2 for a in amp)
        assert abs(norm - 1.0) < 1e-12, f"cphase norm fails at phi={phi}"
    print("  [ok] Two-c-bit controlled phase preserves normalisation")


def test_cphase_nontrivial():
    """c-phase(pi) on balanced inputs produces a non-factorisable amplitude."""
    cb_c = CBit(x=1.0, phi=0.0)
    cb_t = CBit(x=1.0, phi=0.0)
    amp = two_cbit_cphase(cb_c, cb_t, math.pi)
    # Check non-factorisability: reshape to 2x2 and compute rank.
    A = amp.reshape(2, 2)
    U, s, Vh = np.linalg.svd(A)
    # Entangled iff more than one non-zero singular value
    s_sorted = sorted(s, reverse=True)
    assert s_sorted[1] > 1e-6, \
        f"cphase(pi) on balanced should entangle; singular values {s_sorted}"
    print(f"  [ok] CPhase(pi) entangles balanced pair; sing. vals = "
          f"{s_sorted[0]:.3f}, {s_sorted[1]:.3f}")


# =========================================================================
#  §9  BELL VERTEX IN THE C-BIT FRAMEWORK
# =========================================================================
#
#   In the t-bit doc, the Bell vertex is a scalar (x=2) arising from the
#   interior law. Here we verify it has a natural two-c-bit realisation.
#   Standard: the Bell state |Phi+> = (|00> + |11>)/sqrt(2) has full
#   entanglement (Schmidt rank 2, equal singular values). Check that the
#   c-bit framework produces this via Hadamard on control + CNOT.

def two_cbit_CNOT_standard(amp: np.ndarray) -> np.ndarray:
    """Standard CNOT on 2-cbit amplitude vector in basis |00>,|01>,|10>,|11>.
    Control = bit 1 (MSB), target = bit 0 (LSB). Flips target iff control=1."""
    return np.array([amp[0], amp[1], amp[3], amp[2]])


def test_bell_state_construction():
    """|Phi+> = CNOT . (H x I) . |00>.  Schmidt rank 2, equal singular values."""
    # Start with |00>
    cb_c = CBit(alpha=1.0, beta=0.0)
    cb_t = CBit(alpha=1.0, beta=0.0)
    # Apply H to control
    cb_c = cgate_H(cb_c)
    # Joint amplitudes
    a_c, b_c = cb_c.alpha, cb_c.beta
    a_t, b_t = cb_t.alpha, cb_t.beta
    amp = np.array([a_c * a_t, a_c * b_t, b_c * a_t, b_c * b_t])
    # Apply CNOT
    amp = two_cbit_CNOT_standard(amp)
    # Expected Bell state: (|00> + |11>)/sqrt(2), i.e. (1/sqrt(2), 0, 0, 1/sqrt(2))
    expected = np.array([1 / math.sqrt(2), 0, 0, 1 / math.sqrt(2)])
    assert np.allclose(amp, expected, atol=1e-12), f"Bell state: got {amp}"

    # Schmidt decomposition: reshape to 2x2 matrix and SVD
    A = amp.reshape(2, 2)
    _, sv, _ = np.linalg.svd(A)
    # Maximal entanglement: both singular values = 1/sqrt(2)
    assert abs(sv[0] - 1 / math.sqrt(2)) < 1e-12
    assert abs(sv[1] - 1 / math.sqrt(2)) < 1e-12
    print(f"  [ok] Bell state |Phi+> from H + CNOT; Schmidt vals = "
          f"{sv[0]:.4f}, {sv[1]:.4f}  (max entanglement)")


def test_bell_vertex_x_is_pole_product():
    """
    Translate the Bell vertex claim x=2 from the interior law into the
    c-bit framework: the state |Phi+> has marginal mu on EITHER c-bit
    equal to 1/2 (by symmetric entanglement), which corresponds to x=1
    on each marginal. The product x_C * x_T = 1 * 1 = 1 is the TetA
    picture. The x=2 scalar comes from the INTERIOR (TetB) law:
        x(1 - mu_B)^2 = mu_B  with mu_B = 1/2  -> x = 2.
    This connects the entangled-state marginal (mu=1/2) to its
    SUBSPACE acceleration ratio (x=2), not the spatial one (x=1).
    """
    # Construct |Phi+>, trace out the target, get reduced density matrix
    amp = np.array([1 / math.sqrt(2), 0, 0, 1 / math.sqrt(2)])
    A = amp.reshape(2, 2)
    # Reduced density on the control: rho_C = A A^dagger
    rho_C = A @ A.conj().T
    mu_marginal = float(np.real(rho_C[0, 0]))
    # Should be 1/2 by symmetry
    assert abs(mu_marginal - 0.5) < 1e-12, f"marginal mu = {mu_marginal}"

    # Spatial x from marginal: x_A = mu/(1-mu) = 1
    x_spatial = mu_marginal / (1.0 - mu_marginal)
    # Subspace x from interior law: x_B such that x_B * (1 - mu)^2 = mu
    # At mu=1/2: x_B * (1/4) = 1/2, so x_B = 2
    x_subspace = mu_marginal / (1.0 - mu_marginal) ** 2
    assert abs(x_subspace - 2.0) < 1e-12
    print(f"  [ok] Bell state marginal: mu=1/2, x_spatial=1 (MOND ring), "
          f"x_subspace=2 (Bell vertex)")


